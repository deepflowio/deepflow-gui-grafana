const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const { test } = require('node:test')
const assert = require('node:assert/strict')
const source = readFileSync(join(__dirname, 'src/utils/dataStreamer.ts'), 'utf8')
  .replace('private dataQueue: string[]', 'dataQueue')
  .replace('private isEnded', 'isEnded')
  .replace('private outputInterval: number | undefined', 'outputInterval')
  .replace(/onEnd: \(\) => void/g, 'onEnd')
  .replace('data: string', 'data')
  .replace('callback: (char: string) => void, frequency: number', 'callback, frequency')
  .replace(' as string', '')
  .replace('private cleanup()', 'cleanup()')
  .replace('export default DataStreamer', '')
const Stream = new Function(`${source}; return DataStreamer`)()
test('accepts a large chunk without exceeding argument limits', () => {
  const stream = new Stream(() => {})
  const text = 'a'.repeat(200000) + '😀'
  stream.write(text)
  assert.equal(stream.dataQueue.join(''), text)
  assert.equal(stream.dataQueue.length, 200001)
})
